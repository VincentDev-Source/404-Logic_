export function normalizeCityName(rawCity) {
  if (!rawCity) return 'Kota Malang';
  const clean = String(rawCity).trim();
  
  // Check exact match in list
  const found = INDONESIAN_CITIES.find(c => c.name.toLowerCase() === clean.toLowerCase());
  if (found) return found.name;

  // Check partial match
  const partial = INDONESIAN_CITIES.find(c => c.name.toLowerCase().includes(clean.toLowerCase()) || clean.toLowerCase().includes(c.name.toLowerCase()));
  if (partial) return partial.name;

  return clean;
}
